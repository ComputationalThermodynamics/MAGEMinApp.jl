function get_ph_list()

    # hidden phases
    hidden_pp = vcat("O2", ALWAYS_ACTIVE_PP)

    # generated by MAGEMin_C from the library + the Warr (2021) mapping + SOLVUS_FAMILY
    magemin_dir = joinpath(pkgdir(MAGEMin_C), "julia")
    dict_em     = JSON.parsefile(joinpath(magemin_dir, "em_name.json"))
    dict_ss     = JSON.parsefile(joinpath(magemin_dir, "ss_name.json"))

    file_path   = joinpath(pkg_dir,"src","./tools/OL12_KDs_g52l63.json")
    dict_OL12_KDs_g52l63     = JSON.parsefile(file_path)
    file_path   = joinpath(pkg_dir,"src","./tools/OL12_KDs_g63.json")
    dict_OL12_KDs_g63     = JSON.parsefile(file_path)
    file_path   = joinpath(pkg_dir,"src","./tools/OL12_KDs_l52.json")
    dict_OL12_KDs_l52     = JSON.parsefile(file_path)

    db_inf      = retrieve_solution_phase_information("ig");
    
    return dict_ss, hidden_pp, dict_em, dict_OL12_KDs_l52, dict_OL12_KDs_g63, dict_OL12_KDs_g52l63, db_inf
end

"""
    DB_MENU_GROUPS

    Database-selector layout: which databases appear in the dropdown, under which heading
    and in which order. Purely presentational - the databases themselves, their acronyms
    and their names come from `MAGEMin_C.MAGEMIN_DATABASES`. Dropping an acronym from
    here hides it from the interface without removing it from the library.
"""
const DB_MENU_GROUPS = [
    "- PUBLISHED DATABASE -"  => ["mp", "mb", "ig", "igd", "igad", "um"],
    "- BERMAN EOS DATABASE -" => ["po"],
    "- MANTLE DATABASE -"     => [(ENABLE_IGM ? ["igm"] : String[])..., "mtl", "sb11", "sb21", "sb24"],
    "- CUSTOM DATABASE -"     => ["ume", "mpe", "mbe", "all"],
    (ENABLE_MELTS ? ["- MELTS DATABASE -" => ["pMELTS", "rMELTS"]] : [])...,
]

"""
    DB_MENU_LABELS

    Shorter dropdown captions for databases whose full `MAGEMin_C` name does not fit the
    selector. Any acronym left out here is shown under its full name.
"""
const DB_MENU_LABELS = Dict(
    "ig"   => "Igneous (Green et al., 2025, after H18)",
    "igd"  => "Igneous dry (Su et al., 2026, after T21)",
    "igm"  => "Igneous mantle (Rinaldi et al., 2026)",
    "ume"  => "Ultramafic extended (Evans & Frost., 2021)",
    "mpe"  => "Metapelite extended (White et al., 2014, Green et al., 2016, Evans & Frost., 2021)",
    "mbe"  => "Metabasite extended (Green et al., 2016, Diener et al., 2007)",
    "all"  => "Global TC dataset",
)

db_menu_label(dtb::String) = get(DB_MENU_LABELS, dtb, get_db_label(dtb))

"""
    DB_STAGED

    Database acronyms the interface already carries data for (predefined bulk-rock rows,
    commented-out selector entries) but which MAGEMin does not implement yet. They are
    accepted by the bulk-file importer so work in progress on them keeps loading; they
    are not in `DB_MENU_GROUPS`, so they stay out of the selector until the library
    grows them and they turn up in `get_db_list()` on their own.
